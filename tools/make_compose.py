"""Writes compose.yaml and compose.mounts.yaml: one inference server, N instance containers and a monitor, for Docker Desktop.

Run from the repository root: python tools/make_compose.py --streams 16. The file needs TRAFFIC_INFERENCE_KEY in the environment.
"""
from __future__ import annotations

import argparse
from pathlib import Path

V3 = Path(__file__).resolve().parents[1]
CLIP = "pexels-36304379.mp4"
SOCKET = "/run/traffic/server.sock"


def _list(*items: str) -> str:
    """Items as a quoted YAML flow sequence, the form compose accepts for a command."""
    return "[" + ", ".join(f'"{item}"' for item in items) + "]"


def render(streams: int, loops: int = 2) -> str:
    """The text of compose.yaml: a GPU server, one container per stream and a read-only monitor.

    Instances share the server's process namespace (CUDA IPC needs it, and it lets GPU memory be attributed to each
    process) and a socket volume. Only
    instance0 has a build section; the others reuse its image. The file requires TRAFFIC_INFERENCE_KEY when run."""
    lines = [
        f"# Generated by tools/make_compose.py --streams {streams}. Regenerate rather than edit.",
        "# Build: docker compose build. Run: docker compose up. Between runs: docker compose down -v (clears the logs).",
        "name: traffic-v3",
        "x-gpu: &gpu",
        "  deploy:",
        "    resources:",
        "      reservations:",
        "        devices:",
        "          - driver: nvidia",
        "            count: all",
        "            capabilities: [gpu]",
        "  restart: \"no\"",
        "x-environment: &environment",
        "  TRAFFIC_INFERENCE_KEY: ${TRAFFIC_INFERENCE_KEY:?set TRAFFIC_INFERENCE_KEY to a random value}",
        "services:",
        "  server:",
        "    <<: *gpu",
        "    build: {context: ., target: server, additional_contexts: {clip: ./data}}",
        "    image: traffic-v3:server",
        "    cap_add: [SYS_PTRACE]",
        "    environment: *environment",
        "    command: " + _list("python", "run_server.py", "--address", SOCKET, "--clients", str(streams),
                                "--stats-file", "/logs/server.log"),
        "    volumes:",
        "      - traffic-run:/run/traffic",
        "      - traffic-logs:/logs",
    ]
    for stream in range(streams):
        build = ["    build: {context: ., target: instance, additional_contexts: {clip: ./data}}"] if stream == 0 else ["    pull_policy: never"]
        lines += [
            f"  instance{stream}:",
            "    <<: *gpu",
            *build,
            "    image: traffic-v3:instance",
            '    pid: "service:server"',
            "    depends_on: [server]",
            "    environment: *environment",
            "    command: " + _list("python", "run_instance.py", "--address", SOCKET, "--stream", str(stream),
                                    "--no-display", "--loops", str(loops), "--input", f"/data/{CLIP}",
                                    "--stats-file", f"/logs/instance{stream}.log"),
            "    volumes:",
            "      - traffic-run:/run/traffic",
            "      - traffic-logs:/logs",
        ]
    lines += [
        "  monitor:",
        "    image: traffic-v3:instance",
        "    pull_policy: never",
        "    depends_on: [server]",
        "    tty: false",
        "    restart: \"no\"",
        "    command: " + _list("python", "monitor.py", "--logs", "/logs", "--streams", str(streams),
                                "--period-s", "2"),
        "    volumes:",
        "      - traffic-logs:/logs:ro",
        "volumes:",
        "  traffic-run:",
        "  traffic-logs:",
    ]
    return "\n".join(lines) + "\n"


def render_mounts(streams: int) -> str:
    """The text of compose.mounts.yaml, an optional override that mounts local models and clips read-only."""
    lines = [
        f"# Generated by tools/make_compose.py --streams {streams}. Regenerate rather than edit.",
        "# Optional override: use your own models or clip. docker compose -f compose.yaml -f compose.mounts.yaml up",
        "services:",
        "  server:",
        "    volumes:",
        "      - ./models:/app/models:ro",
    ]
    for stream in range(streams):
        lines += [f"  instance{stream}:", "    volumes:", "      - ./data:/data:ro"]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Writes both compose files; a stream count below 1 is a usage error."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--streams", type=int, default=16)
    parser.add_argument("--output", type=Path, default=V3 / "compose.yaml")
    parser.add_argument("--mounts-output", type=Path, default=V3 / "compose.mounts.yaml")
    args = parser.parse_args()
    if args.streams < 1:
        parser.error("--streams must be at least 1")
    args.output.write_text(render(args.streams), encoding="utf-8", newline="\n")
    args.mounts_output.write_text(render_mounts(args.streams), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
